const root = document.documentElement;
const description = document.querySelector('meta[name="description"]');
const languageButtons = document.querySelectorAll('[data-language]');
const motionButton = document.querySelector('[data-motion-toggle]');
const motionLabel = motionButton?.querySelector('span:last-child');
const lightChamber = document.querySelector('.light-chamber');
const bookingForm = document.querySelector('#booking-form');
const bookingService = document.querySelector('#booking-service');
const bookingStatus = document.querySelector('#booking-status');
const motionPreference = window.matchMedia('(prefers-reduced-motion: reduce)');
const bookingEmail = 'hamdihajiali76@gmail.com';
const whatsappNumber = '905377423671';
let language = 'ar';
let motionEnabled = !motionPreference.matches;

try { language = localStorage.getItem('hamdi-language') || 'ar'; } catch (error) { language = 'ar'; }

function updateMotionControl() {
  const copy = translations[language];
  if (!motionButton || !motionLabel) return;
  const available = !motionPreference.matches;
  motionButton.disabled = !available;
  motionButton.setAttribute('aria-pressed', String(motionEnabled && available));
  motionLabel.textContent = available ? (motionEnabled ? copy.motionOn : copy.motionOff) : copy.motionUnavailable;
  document.body.classList.toggle('motion-paused', !motionEnabled || !available);
}

function setLanguage(nextLanguage) {
  const copy = translations[nextLanguage];
  if (!copy) return;
  language = nextLanguage;
  root.lang = language;
  root.dir = language === 'ar' ? 'rtl' : 'ltr';
  document.title = copy.pageTitle;
  description?.setAttribute('content', copy.description);
  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const value = copy[element.dataset.i18n];
    if (value) element.innerHTML = value;
  });
  document.querySelectorAll('[data-i18n-html]').forEach((element) => {
    const value = copy[element.dataset.i18nHtml];
    if (value) element.innerHTML = value;
  });
  document.querySelectorAll('[data-i18n-aria]').forEach((element) => {
    const value = copy[element.dataset.i18nAria];
    if (value) element.setAttribute('aria-label', value);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
    const value = copy[element.dataset.i18nPlaceholder];
    if (value) element.setAttribute('placeholder', value);
  });
  languageButtons.forEach((button) => {
    const active = button.dataset.language === language;
    button.classList.toggle('is-active', active);
    button.setAttribute('aria-pressed', String(active));
  });
  updateMotionControl();
  try { localStorage.setItem('hamdi-language', language); } catch (error) { /* Storage is optional. */ }
}

function setMotion(nextState) {
  motionEnabled = Boolean(nextState) && !motionPreference.matches;
  updateMotionControl();
}

function openGmailDraft(subject, message) {
  const url = `https://mail.google.com/mail/?view=cm&fs=1&to=${encodeURIComponent(bookingEmail)}&su=${encodeURIComponent(subject)}&body=${encodeURIComponent(message)}`;
  const popup = window.open(url, '_blank');
  if (popup) popup.opener = null;
  else window.location.href = url;
}

function buildBookingMessage(formData) {
  const copy = translations[language];
  const service = String(formData.get('service') || '');
  const serviceTitle = {
    color: copy.serviceColorTitle,
    graduation: copy.serviceGraduationTitle,
    hair: copy.serviceHairTitle,
    id: copy.serviceIdTitle
  }[service] || service;
  const name = String(formData.get('name') || '').trim();
  const phone = String(formData.get('phone') || '').trim();
  const details = String(formData.get('details') || '').trim();
  const lines = [
    copy.bookingMessageTitle,
    '',
    `${copy.bookingMessageService}: ${serviceTitle}`,
    `${copy.bookingMessageName}: ${name}`,
    phone && `${copy.bookingMessagePhone}: ${phone}`,
    details && `${copy.bookingMessageDetails}: ${details}`
  ];
  return { message: lines.filter(Boolean).join('\n'), serviceTitle };
}

languageButtons.forEach((button) => button.addEventListener('click', () => setLanguage(button.dataset.language)));
motionButton?.addEventListener('click', () => setMotion(!motionEnabled));

document.querySelectorAll('[data-booking-service]').forEach((button) => button.addEventListener('click', () => {
  if (!bookingService) return;
  bookingService.value = button.dataset.bookingService;
  document.querySelector('#contact')?.scrollIntoView({ behavior: motionPreference.matches ? 'auto' : 'smooth', block: 'start' });
  window.setTimeout(() => bookingService.focus({ preventScroll: true }), motionPreference.matches ? 0 : 500);
}));

bookingForm?.addEventListener('submit', (event) => {
  event.preventDefault();
  if (!bookingForm.reportValidity()) return;
  const copy = translations[language];
  const channel = event.submitter?.dataset.bookingChannel || 'email';
  const { message, serviceTitle } = buildBookingMessage(new FormData(bookingForm));
  if (channel === 'email') {
    openGmailDraft(`${copy.bookingEmailSubject} — ${serviceTitle}`, message);
    bookingStatus.textContent = copy.bookingStatusEmail;
    return;
  }
  const url = `https://wa.me/${whatsappNumber}?text=${encodeURIComponent(message)}`;
  const popup = window.open(url, '_blank');
  if (popup) popup.opener = null;
  else window.location.href = url;
  bookingStatus.textContent = copy.bookingStatusWhatsapp;
});

if (lightChamber && !motionPreference.matches) {
  lightChamber.addEventListener('pointermove', (event) => {
    if (event.pointerType === 'touch' || !motionEnabled) return;
    const bounds = lightChamber.getBoundingClientRect();
    const x = (event.clientX - bounds.left) / bounds.width;
    const y = (event.clientY - bounds.top) / bounds.height;
    lightChamber.style.setProperty('--pointer-x', `${Math.round(x * 100)}%`);
    lightChamber.style.setProperty('--pointer-y', `${Math.round(y * 100)}%`);
    lightChamber.style.setProperty('--tilt-x', `${((0.5 - y) * 7).toFixed(2)}deg`);
    lightChamber.style.setProperty('--tilt-y', `${((x - 0.5) * 9).toFixed(2)}deg`);
  });
  lightChamber.addEventListener('pointerleave', () => {
    lightChamber.style.setProperty('--pointer-x', '50%');
    lightChamber.style.setProperty('--pointer-y', '50%');
    lightChamber.style.setProperty('--tilt-x', '0deg');
    lightChamber.style.setProperty('--tilt-y', '0deg');
  });
}

motionPreference.addEventListener('change', (event) => { if (event.matches) setMotion(false); else updateMotionControl(); });
setLanguage(translations[language] ? language : 'ar');

