function initImmersiveGallery() {
  const gallery = document.querySelector('[data-immersive-gallery]');
  if (!gallery) return;
  const cards = Array.from(gallery.querySelectorAll('.gallery-card'));
  const current = document.getElementById('galleryCurrent');
  const total = document.getElementById('galleryTotal');
  const progress = document.getElementById('galleryProgress');
  const progressFill = progress?.querySelector('span');
  const buttons = Array.from(document.querySelectorAll('[data-gallery-step]'));
  if (!cards.length) return;
  if (total) total.textContent = String(cards.length).padStart(2, '0');
  if (progress) progress.setAttribute('aria-valuemax', String(cards.length));

  let activeIndex = 0;
  const reducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  const updateActive = (index) => {
    const safeIndex = Math.max(0, Math.min(cards.length - 1, index));
    if (safeIndex === activeIndex && cards[safeIndex].classList.contains('is-active')) return;
    activeIndex = safeIndex;
    cards.forEach((card, cardIndex) => {
      const isActive = cardIndex === activeIndex;
      card.classList.toggle('is-active', isActive);
      if (isActive) card.setAttribute('aria-current', 'true');
      else card.removeAttribute('aria-current');
    });
    if (current) current.textContent = String(activeIndex + 1).padStart(2, '0');
    if (progressFill) progressFill.style.transform = 'scaleX(' + ((activeIndex + 1) / cards.length) + ')';
    if (progress) progress.setAttribute('aria-valuenow', String(activeIndex + 1));
    buttons.forEach((button) => {
      const step = Number(button.getAttribute('data-gallery-step'));
      button.disabled = step < 0 ? activeIndex === 0 : activeIndex === cards.length - 1;
    });
  };

  const goTo = (index) => {
    const nextIndex = Math.max(0, Math.min(cards.length - 1, index));
    cards[nextIndex].scrollIntoView({
      behavior: reducedMotion ? 'auto' : 'smooth',
      block: 'nearest',
      inline: 'center'
    });
    updateActive(nextIndex);
  };

  buttons.forEach((button) => {
    button.addEventListener('click', () => goTo(activeIndex + Number(button.getAttribute('data-gallery-step'))));
  });

  if ('IntersectionObserver' in window) {
    const observer = new IntersectionObserver((entries) => {
      const visible = entries
        .filter((entry) => entry.isIntersecting)
        .sort((a, b) => b.intersectionRatio - a.intersectionRatio)[0];
      if (visible) updateActive(cards.indexOf(visible.target));
    }, { root: gallery, threshold: [0.2, 0.45, 0.65, 0.82] });
    cards.forEach((card) => observer.observe(card));
  } else {
    gallery.addEventListener('scroll', () => {
      const center = gallery.getBoundingClientRect().left + gallery.clientWidth / 2;
      let closest = 0;
      cards.forEach((card, index) => {
        const box = card.getBoundingClientRect();
        if (Math.abs(box.left + box.width / 2 - center) < Math.abs(cards[closest].getBoundingClientRect().left + cards[closest].getBoundingClientRect().width / 2 - center)) closest = index;
      });
      updateActive(closest);
    }, { passive: true });
  }

  gallery.addEventListener('keydown', (event) => {
    if (event.key !== 'ArrowLeft' && event.key !== 'ArrowRight') return;
    event.preventDefault();
    goTo(activeIndex + (event.key === 'ArrowRight' ? 1 : -1));
  });

  let pointerDown = false;
  let dragged = false;
  let startX = 0;
  let startScroll = 0;
  let suppressClick = false;
  gallery.addEventListener('pointerdown', (event) => {
    if (event.pointerType !== 'mouse' || event.button !== 0 || event.target.closest('button')) return;
    pointerDown = true;
    dragged = false;
    startX = event.clientX;
    startScroll = gallery.scrollLeft;
  });
  gallery.addEventListener('pointermove', (event) => {
    if (!pointerDown) return;
    const delta = event.clientX - startX;
    if (!dragged && Math.abs(delta) > 7) {
      dragged = true;
      gallery.classList.add('is-dragging');
      gallery.setPointerCapture?.(event.pointerId);
    }
    if (dragged) {
      gallery.scrollLeft = startScroll - delta;
      event.preventDefault();
    }
  });
  const finishDrag = (event) => {
    if (!pointerDown) return;
    pointerDown = false;
    gallery.classList.remove('is-dragging');
    if (dragged) {
      suppressClick = true;
      window.setTimeout(() => { suppressClick = false; }, 180);
    }
    if (gallery.hasPointerCapture?.(event.pointerId)) gallery.releasePointerCapture(event.pointerId);
  };
  gallery.addEventListener('pointerup', finishDrag);
  gallery.addEventListener('pointercancel', finishDrag);
  gallery.addEventListener('click', (event) => {
    if (!suppressClick) return;
    event.preventDefault();
    event.stopImmediatePropagation();
    suppressClick = false;
  }, true);

  updateActive(0);
}

document.addEventListener('DOMContentLoaded', initImmersiveGallery);


function initBookingDatePicker() {
  const dateInput = document.getElementById('preferredDate');
  const field = document.getElementById('preferredDateField');
  if (!dateInput || !field) return;

  const today = new Date();
  today.setHours(0, 0, 0, 0);
  const formatISO = (year, month, day) => [
    year,
    String(month + 1).padStart(2, '0'),
    String(day).padStart(2, '0')
  ].join('-');
  const todayISO = formatISO(today.getFullYear(), today.getMonth(), today.getDate());
  const firstAllowedMonth = new Date(today.getFullYear(), today.getMonth(), 1);
  let visibleMonth = new Date(firstAllowedMonth);

  const currentLocale = () => ({
    ar: 'ar',
    tr: 'tr-TR',
    en: 'en-US'
  }[document.documentElement.lang] || 'en-US');
  const currentCopy = () => translations[document.documentElement.lang] || translations.en;
  const parseISO = (iso) => {
    const [year, month, day] = iso.split('-').map(Number);
    return new Date(Date.UTC(year, month - 1, day, 12));
  };
  const formatLocalizedDate = (iso) => new Intl.DateTimeFormat(currentLocale(), {
    dateStyle: 'long',
    calendar: 'gregory',
    timeZone: 'UTC'
  }).format(parseISO(iso));

  const calendar = document.createElement('div');
  calendar.id = 'bookingCalendar';
  calendar.className = 'booking-calendar';
  calendar.setAttribute('role', 'dialog');
  calendar.setAttribute('aria-modal', 'false');
  calendar.hidden = true;
  calendar.innerHTML =
    '<div class="booking-calendar-heading">' +
      '<button type="button" class="booking-calendar-nav" data-calendar-action="previous" aria-label=""><span aria-hidden="true">‹</span></button>' +
      '<strong class="booking-calendar-month" aria-live="polite"></strong>' +
      '<button type="button" class="booking-calendar-nav" data-calendar-action="next" aria-label=""><span aria-hidden="true">›</span></button>' +
    '</div>' +
    '<div class="booking-calendar-weekdays" aria-hidden="true"></div>' +
    '<div class="booking-calendar-days"></div>' +
    '<div class="booking-calendar-footer"><button type="button" class="booking-calendar-today" data-calendar-action="today"></button></div>';
  field.appendChild(calendar);

  const monthTitle = calendar.querySelector('.booking-calendar-month');
  const weekdayRow = calendar.querySelector('.booking-calendar-weekdays');
  const dayGrid = calendar.querySelector('.booking-calendar-days');
  const previousButton = calendar.querySelector('[data-calendar-action="previous"]');
  const nextButton = calendar.querySelector('[data-calendar-action="next"]');
  const todayButton = calendar.querySelector('[data-calendar-action="today"]');

  function renderCalendar() {
    const locale = currentLocale();
    const copy = currentCopy();
    calendar.lang = locale;
    calendar.dir = document.documentElement.dir;
    calendar.setAttribute('aria-label', copy.calendarTitle);
    previousButton.setAttribute('aria-label', copy.calendarPrev);
    nextButton.setAttribute('aria-label', copy.calendarNext);
    todayButton.textContent = copy.calendarToday;

    const year = visibleMonth.getFullYear();
    const month = visibleMonth.getMonth();
    const monthDate = new Date(Date.UTC(year, month, 1, 12));
    monthTitle.textContent = new Intl.DateTimeFormat(locale, {
      month: 'long',
      year: 'numeric',
      calendar: 'gregory',
      timeZone: 'UTC'
    }).format(monthDate);

    let firstDay = document.documentElement.lang === 'ar' ? 6 : document.documentElement.lang === 'tr' ? 1 : 0;
    try {
      const localeInfo = new Intl.Locale(locale);
      const localeFirstDay = localeInfo.weekInfo?.firstDay || localeInfo.getWeekInfo?.().firstDay;
      if (localeFirstDay) firstDay = localeFirstDay % 7;
    } catch (error) {}

    weekdayRow.replaceChildren();
    const weekdayFormatter = new Intl.DateTimeFormat(locale, { weekday: 'short', timeZone: 'UTC' });
    for (let index = 0; index < 7; index += 1) {
      const weekdayIndex = (firstDay + index) % 7;
      const weekday = document.createElement('span');
      weekday.textContent = weekdayFormatter.format(new Date(Date.UTC(2023, 0, 1 + weekdayIndex, 12)));
      weekdayRow.appendChild(weekday);
    }

    dayGrid.replaceChildren();
    const leadingDays = (new Date(year, month, 1).getDay() - firstDay + 7) % 7;
    for (let index = 0; index < leadingDays; index += 1) {
      const spacer = document.createElement('span');
      spacer.setAttribute('aria-hidden', 'true');
      dayGrid.appendChild(spacer);
    }

    const dayFormatter = new Intl.NumberFormat(locale, { useGrouping: false });
    const daysInMonth = new Date(year, month + 1, 0).getDate();
    for (let day = 1; day <= daysInMonth; day += 1) {
      const iso = formatISO(year, month, day);
      const dateButton = document.createElement('button');
      dateButton.type = 'button';
      dateButton.className = 'booking-calendar-day';
      dateButton.textContent = dayFormatter.format(day);
      dateButton.dataset.date = iso;
      dateButton.setAttribute('aria-label', formatLocalizedDate(iso));
      dateButton.setAttribute('aria-pressed', String(iso === dateInput.dataset.isoDate));
      dateButton.disabled = iso < todayISO;
      if (iso === todayISO) dateButton.classList.add('is-today');
      if (iso === dateInput.dataset.isoDate) dateButton.classList.add('is-selected');
      dayGrid.appendChild(dateButton);
    }

    const firstAllowed = visibleMonth.getFullYear() === firstAllowedMonth.getFullYear() &&
      visibleMonth.getMonth() === firstAllowedMonth.getMonth();
    previousButton.disabled = firstAllowed;
  }

  function closeCalendar(returnFocus) {
    calendar.hidden = true;
    dateInput.setAttribute('aria-expanded', 'false');
    if (returnFocus) dateInput.focus();
  }

  function openCalendar(fromKeyboard) {
    const selectedISO = dateInput.dataset.isoDate;
    if (selectedISO) {
      const selectedDate = parseISO(selectedISO);
      visibleMonth = new Date(selectedDate.getUTCFullYear(), selectedDate.getUTCMonth(), 1);
    } else {
      visibleMonth = new Date(firstAllowedMonth);
    }
    renderCalendar();
    calendar.hidden = false;
    dateInput.setAttribute('aria-expanded', 'true');
    if (fromKeyboard) {
      window.requestAnimationFrame(() => {
        const focusDate = dateInput.dataset.isoDate || todayISO;
        const target = calendar.querySelector('[data-date="' + focusDate + '"]:not(:disabled)') ||
          calendar.querySelector('.booking-calendar-day:not(:disabled)');
        if (target) target.focus();
      });
    }
  }

  dateInput.addEventListener('click', () => {
    if (calendar.hidden) openCalendar(false);
    else closeCalendar(false);
  });
  dateInput.addEventListener('keydown', (event) => {
    if (event.key === 'Escape' && !calendar.hidden) {
      event.preventDefault();
      closeCalendar(true);
    } else if (event.key === 'Enter' || event.key === ' ' || event.key === 'ArrowDown') {
      event.preventDefault();
      if (calendar.hidden) openCalendar(true);
    }
  });

  calendar.addEventListener('click', (event) => {
    const actionButton = event.target.closest('[data-calendar-action]');
    if (actionButton) {
      const action = actionButton.dataset.calendarAction;
      if (action === 'previous' && !actionButton.disabled) {
        visibleMonth = new Date(visibleMonth.getFullYear(), visibleMonth.getMonth() - 1, 1);
        renderCalendar();
      } else if (action === 'next') {
        visibleMonth = new Date(visibleMonth.getFullYear(), visibleMonth.getMonth() + 1, 1);
        renderCalendar();
      } else if (action === 'today') {
        selectDate(todayISO);
      }
      return;
    }

    const dayButton = event.target.closest('[data-date]');
    if (dayButton && !dayButton.disabled) selectDate(dayButton.dataset.date);
  });

  function selectDate(iso) {
    dateInput.dataset.isoDate = iso;
    dateInput.value = formatLocalizedDate(iso);
    dateInput.removeAttribute('aria-invalid');
    dateInput.dispatchEvent(new Event('input', { bubbles: true }));
    dateInput.dispatchEvent(new Event('change', { bubbles: true }));
    closeCalendar(true);
  }

  document.addEventListener('pointerdown', (event) => {
    if (!field.contains(event.target) && !calendar.hidden) closeCalendar(false);
  });

  window.refreshBookingCalendarLocale = () => {
    const selectedISO = dateInput.dataset.isoDate;
    dateInput.lang = currentLocale();
    dateInput.dir = document.documentElement.dir;
    if (selectedISO) dateInput.value = formatLocalizedDate(selectedISO);
    renderCalendar();
  };

  renderCalendar();
}
document.addEventListener('DOMContentLoaded', initBookingDatePicker);



/* The hero photo album gently tilts and turns a page as the visitor explores it. */
function initSignatureAlbumInteraction() {
  const visual = document.querySelector('.hero-visual');
  const scene = visual?.querySelector('.album-scene');
  if (!visual || !scene) return;

  const finePointer = window.matchMedia('(hover: hover) and (pointer: fine)').matches;
  const reducedMotion = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  if (reducedMotion) return;

  if (!finePointer) {
    visual.setAttribute('role', 'button');
    visual.setAttribute('tabindex', '0');
    let replayTimer = 0;

    const playPageTurn = () => {
      window.clearTimeout(replayTimer);
      visual.classList.remove('is-album-engaged');
      void visual.offsetWidth;
      visual.classList.add('is-album-engaged');
      replayTimer = window.setTimeout(() => {
        visual.classList.remove('is-album-engaged');
      }, 1550);
    };

    visual.addEventListener('click', playPageTurn);
    visual.addEventListener('keydown', (event) => {
      if (event.key !== 'Enter' && event.key !== ' ') return;
      event.preventDefault();
      playPageTurn();
    });
    return;
  }

  const reset = () => {
    visual.classList.remove('is-album-engaged');
    scene.style.setProperty('--album-pointer-x', '0deg');
    scene.style.setProperty('--album-pointer-y', '0deg');
  };

  visual.addEventListener('pointermove', (event) => {
    const bounds = visual.getBoundingClientRect();
    if (!bounds.width || !bounds.height) return;
    const x = ((event.clientX - bounds.left) / bounds.width - 0.5) * 2;
    const y = ((event.clientY - bounds.top) / bounds.height - 0.5) * 2;
    scene.style.setProperty('--album-pointer-x', (y * -4.5).toFixed(2) + 'deg');
    scene.style.setProperty('--album-pointer-y', (x * 6).toFixed(2) + 'deg');
    visual.classList.add('is-album-engaged');
  }, { passive: true });

  visual.addEventListener('pointerleave', reset);
  visual.addEventListener('pointercancel', reset);
}
if (document.readyState === 'loading') {
  document.addEventListener('DOMContentLoaded', initSignatureAlbumInteraction, { once: true });
} else {
  initSignatureAlbumInteraction();
}

function initSiteSearch() {
  const trigger = document.getElementById('siteSearchTrigger');
  const dialog = document.getElementById('siteSearchDialog');
  const closeButton = document.getElementById('siteSearchClose');
  const form = document.getElementById('siteSearchForm');
  const input = document.getElementById('siteSearchInput');
  const hint = document.getElementById('siteSearchHint');
  const results = document.getElementById('siteSearchResults');
  if (!trigger || !dialog || !form || !input || !results) return;

  const normalize = (value) => String(value || '')
    .normalize('NFD')
    .replace(/[\\u0300-\\u036f]/g, '')
    .toLocaleLowerCase()
    .replace(/[أإآ]/g, 'ا')
    .replace(/ى/g, 'ي')
    .replace(/ة/g, 'ه')
    .replace(/\\s+/g, ' ')
    .trim();

  const getEntries = () => Array.from(document.querySelectorAll('#work .gallery-card, #services .service, #pricing .price-card'))
    .map((node) => {
      const isGallery = node.matches('#work .gallery-card');
      const isService = node.matches('#services .service');
      const title = (node.querySelector('.card-caption, h3')?.textContent || '').replace(/↗/g, '').trim();
      const imageAlt = node.querySelector('img')?.alt || '';
      const detail = node.querySelector('.card-number, .price-option, p')?.textContent?.trim() || '';
      const type = isGallery ? 'searchGroupGallery' : isService ? 'searchGroupService' : 'searchGroupPricing';
      return { node, title, detail, type, haystack: normalize([node.textContent, imageAlt].join(' ')), isGallery };
    });

  const labels = () => translations[document.documentElement.lang] || translations.ar;

  function renderResults() {
    const copy = labels();
    const query = normalize(input.value);
    results.replaceChildren();
    if (!query) {
      hint.textContent = copy.searchEmpty;
      return;
    }

    const terms = query.split(' ').filter(Boolean);
    const matches = getEntries().filter((entry) => terms.every((term) => entry.haystack.includes(term))).slice(0, 10);
    if (!matches.length) {
      hint.textContent = copy.searchNoResults;
      return;
    }

    hint.textContent = '';
    matches.forEach((entry) => {
      const button = document.createElement('button');
      button.type = 'button';
      button.className = 'site-search-result';
      button.setAttribute('role', 'option');

      const content = document.createElement('span');
      content.className = 'site-search-result-copy';
      const kind = document.createElement('small');
      kind.className = 'site-search-result-kind';
      kind.textContent = copy[entry.type];
      const title = document.createElement('strong');
      title.textContent = entry.title || entry.detail || copy[entry.type];
      const detail = document.createElement('span');
      detail.className = 'site-search-result-detail';
      detail.textContent = entry.title && entry.detail !== entry.title ? entry.detail : '';
      content.append(kind, title, detail);

      const arrow = document.createElement('span');
      arrow.className = 'site-search-result-arrow';
      arrow.setAttribute('aria-hidden', 'true');
      arrow.textContent = '↗';
      button.append(content, arrow);
      button.addEventListener('click', () => {
        dialog.close();
        entry.node.scrollIntoView({
          behavior: window.matchMedia('(prefers-reduced-motion: reduce)').matches ? 'auto' : 'smooth',
          block: 'center',
          inline: 'center'
        });
        if (entry.isGallery) entry.node.click();
      });
      results.appendChild(button);
    });
  }

  trigger.addEventListener('click', () => {
    if (!dialog.open) dialog.showModal();
    input.value = '';
    renderResults();
    window.requestAnimationFrame(() => input.focus());
  });
  closeButton?.addEventListener('click', () => dialog.close());
  form.addEventListener('submit', (event) => {
    event.preventDefault();
    renderResults();
  });
  input.addEventListener('input', renderResults);
  dialog.addEventListener('click', (event) => {
    if (event.target === dialog) dialog.close();
  });
}
document.addEventListener('DOMContentLoaded', initSiteSearch);
