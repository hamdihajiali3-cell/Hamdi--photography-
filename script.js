const root = document.documentElement;
const title = document.querySelector("title");
const languageButtons = document.querySelectorAll("[data-language]");

function setLanguage(language) {
  const dictionary = translations[language];
  const isArabic = language === "ar";

  root.lang = language;
  root.dir = isArabic ? "rtl" : "ltr";
  title.textContent = isArabic ? "Hamdi Photography | خدمات تصوير" : "Hamdi Photography | Fotoğraf hizmetleri";

  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (dictionary[key]) element.innerHTML = dictionary[key];
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((element) => {
    const key = element.dataset.i18nAria;
    if (dictionary[key]) element.setAttribute("aria-label", dictionary[key]);
  });

  languageButtons.forEach((button) => {
    const isSelected = button.dataset.language === language;
    button.classList.toggle("is-active", isSelected);
    button.setAttribute("aria-pressed", String(isSelected));
  });

  localStorage.setItem("hamdi-language", language);
}

languageButtons.forEach((button) => {
  button.addEventListener("click", () => setLanguage(button.dataset.language));
});

document.querySelectorAll("[data-service]").forEach((link) => {
  link.addEventListener("click", () => {
    const chosenService = link.dataset.service;
    document.body.dataset.chosenService = chosenService;
  });
});

const savedLanguage = localStorage.getItem("hamdi-language");
if (savedLanguage && translations[savedLanguage]) setLanguage(savedLanguage);

