function initGalleryFocusEffect() {
  const cards = Array.from(document.querySelectorAll('.gallery-card'));
  if (!cards.length) return;

  const language = document.documentElement.lang.slice(0, 2);
  const focusLabel = language === 'ar'
    ? 'اكتمل التركيز'
    : language === 'tr'
      ? 'ODAK KİLİTLENDİ'
      : 'FOCUS LOCKED';

  cards.forEach((card) => {
    const target = document.createElement('span');
    target.className = 'gallery-focus-target';
    target.setAttribute('aria-hidden', 'true');

    const status = document.createElement('span');
    status.className = 'gallery-focus-status';
    status.textContent = focusLabel;
    target.appendChild(status);
    card.appendChild(target);

    card.addEventListener('pointermove', (event) => {
      if (event.pointerType === 'touch') return;
      const bounds = card.getBoundingClientRect();
      const horizontal = Math.min(92, Math.max(8, (event.clientX - bounds.left) / bounds.width * 100));
      const vertical = Math.min(82, Math.max(12, (event.clientY - bounds.top) / bounds.height * 100));
      card.style.setProperty('--focus-x', horizontal.toFixed(1) + '%');
      card.style.setProperty('--focus-y', vertical.toFixed(1) + '%');
      card.classList.add('is-focus-hover');
    });

    card.addEventListener('pointerleave', () => card.classList.remove('is-focus-hover'));
    card.addEventListener('focusin', () => card.classList.add('is-focus-hover'));
    card.addEventListener('focusout', (event) => {
      if (!card.contains(event.relatedTarget)) card.classList.remove('is-focus-hover');
    });
  });

  if (window.matchMedia('(prefers-reduced-motion: reduce)').matches) return;

  const gallery = document.querySelector('#work .gallery');
  if (!gallery) return;

  let galleryVisible = false;
  let activeIndex = -1;
  let cycleTimer = 0;
  let scanTimer = 0;
  let unlockTimer = 0;
  let flashTimer = 0;

  const clearActiveFocus = () => {
    window.clearTimeout(scanTimer);
    window.clearTimeout(unlockTimer);
    window.clearTimeout(flashTimer);
    cards.forEach((card) => card.classList.remove('is-focus-scanning', 'is-focus-locked', 'is-focus-flash'));
  };

  const stopFocusLoop = () => {
    window.clearTimeout(cycleTimer);
    cycleTimer = 0;
    clearActiveFocus();
  };

  const focusNextPhoto = () => {
    cycleTimer = 0;
    if (!galleryVisible || document.hidden) return;
    if (cards.some((card) => card.matches(':hover, :focus-within'))) {
      cycleTimer = window.setTimeout(focusNextPhoto, 900);
      return;
    }

    clearActiveFocus();
    activeIndex = (activeIndex + 1) % cards.length;
    const card = cards[activeIndex];
    const startX = 22 + (activeIndex % 3) * 13;
    const startY = 28 + (activeIndex % 2) * 17;
    const lockX = 53 + (activeIndex % 3) * 9;
    const lockY = 38 + (activeIndex % 2) * 15;

    card.style.setProperty('--focus-start-x', startX + '%');
    card.style.setProperty('--focus-start-y', startY + '%');
    card.style.setProperty('--focus-lock-x', lockX + '%');
    card.style.setProperty('--focus-lock-y', lockY + '%');
    card.classList.add('is-focus-scanning');

    scanTimer = window.setTimeout(() => {
      card.classList.remove('is-focus-scanning');
      card.classList.add('is-focus-locked', 'is-focus-flash');
      flashTimer = window.setTimeout(() => card.classList.remove('is-focus-flash'), 520);
      unlockTimer = window.setTimeout(() => card.classList.remove('is-focus-locked'), 1450);
    }, 1080);

    cycleTimer = window.setTimeout(focusNextPhoto, 3600);
  };

  const startFocusLoop = () => {
    if (!galleryVisible || document.hidden || cycleTimer) return;
    focusNextPhoto();
  };

  if ('IntersectionObserver' in window) {
    const observer = new IntersectionObserver((entries) => {
      galleryVisible = entries.some((entry) => entry.isIntersecting);
      if (galleryVisible) startFocusLoop();
      else stopFocusLoop();
    }, { threshold: 0.16 });
    observer.observe(gallery);
  } else {
    galleryVisible = true;
    startFocusLoop();
  }

  document.addEventListener('visibilitychange', () => {
    if (document.hidden) stopFocusLoop();
    else if (galleryVisible) startFocusLoop();
  });
}

document.addEventListener('DOMContentLoaded', initGalleryFocusEffect);

function initServiceBookingLinks() {
  const select = document.getElementById('sessionType');
  if (!select) return;
  document.querySelectorAll('[data-select-service]').forEach((link) => {
    link.addEventListener('click', () => {
      const key = link.getAttribute('data-select-service');
      const option = Array.from(select.options).find((item) => item.getAttribute('data-i18n-value') === key);
      if (!option) return;
      select.value = option.value;
      select.classList.add('service-prefilled');
    });
  });
  select.addEventListener('change', () => select.classList.remove('service-prefilled'));
}
document.addEventListener('DOMContentLoaded', initServiceBookingLinks);

function initSelectionSound() {
  const AudioContextClass = window.AudioContext || window.webkitAudioContext;
  if (!AudioContextClass) return;

  let audioContext;
  const playSelectionSound = () => {
    try {
      audioContext ||= new AudioContextClass();
      if (audioContext.state === 'suspended') void audioContext.resume().catch(() => {});
      const now = audioContext.currentTime;
      const output = audioContext.createGain();
      output.gain.setValueAtTime(0.0001, now);
      output.gain.exponentialRampToValueAtTime(0.035, now + 0.006);
      output.gain.exponentialRampToValueAtTime(0.0001, now + 0.095);
      output.connect(audioContext.destination);

      const click = audioContext.createOscillator();
      click.type = 'triangle';
      click.frequency.setValueAtTime(1480, now);
      click.frequency.exponentialRampToValueAtTime(620, now + 0.07);
      click.connect(output);
      click.start(now);
      click.stop(now + 0.1);

      const sparkle = audioContext.createOscillator();
      const sparkleGain = audioContext.createGain();
      sparkle.type = 'sine';
      sparkle.frequency.setValueAtTime(1760, now + 0.012);
      sparkle.frequency.exponentialRampToValueAtTime(1180, now + 0.055);
      sparkleGain.gain.setValueAtTime(0.0001, now);
      sparkleGain.gain.exponentialRampToValueAtTime(0.22, now + 0.018);
      sparkleGain.gain.exponentialRampToValueAtTime(0.0001, now + 0.065);
      sparkle.connect(sparkleGain);
      sparkleGain.connect(output);
      sparkle.start(now + 0.012);
      sparkle.stop(now + 0.07);
    } catch (error) {
      // Audio is an optional enhancement; keep all selections working if it is unavailable.
    }
  };

  document.addEventListener('click', (event) => {
    const target = event.target instanceof Element ? event.target : null;
    if (!target) return;
    const languageButton = target.closest('.language-button');
    if (languageButton && !languageButton.classList.contains('is-active')) {
      playSelectionSound();
      return;
    }
    if (target.closest('.gallery-card, [data-select-service]')) playSelectionSound();
  }, true);

  let lastTypingSoundAt = 0;
  let typingSoundIndex = 0;
  const playTypingSound = (event) => {
    if (!event.isTrusted || event.isComposing) return;
    const stamp = performance.now();
    if (stamp - lastTypingSoundAt < 28) return;
    lastTypingSoundAt = stamp;

    try {
      audioContext ||= new AudioContextClass();
      if (audioContext.state === 'suspended') void audioContext.resume().catch(() => {});
      const now = audioContext.currentTime;
      const filter = audioContext.createBiquadFilter();
      filter.type = 'lowpass';
      filter.frequency.setValueAtTime(1500, now);
      filter.Q.setValueAtTime(0.65, now);

      const envelope = audioContext.createGain();
      envelope.gain.setValueAtTime(0.0001, now);
      envelope.gain.exponentialRampToValueAtTime(0.045, now + 0.002);
      envelope.gain.exponentialRampToValueAtTime(0.0001, now + 0.038);
      filter.connect(envelope);
      envelope.connect(audioContext.destination);

      const keyTap = audioContext.createOscillator();
      keyTap.type = 'triangle';
      keyTap.frequency.setValueAtTime(470 + (typingSoundIndex % 5) * 22, now);
      keyTap.frequency.exponentialRampToValueAtTime(210, now + 0.034);
      keyTap.connect(filter);
      keyTap.start(now);
      keyTap.stop(now + 0.04);
      typingSoundIndex += 1;
    } catch (error) {
      // Keep typing available when audio is blocked or unsupported.
    }
  };

  document.querySelectorAll('#clientName, #clientMsg').forEach((field) => {
    field.addEventListener('beforeinput', playTypingSound);
  });

  const sessionType = document.getElementById('sessionType');
  sessionType?.addEventListener('change', playSelectionSound);

  window.addEventListener('pagehide', () => {
    if (audioContext && audioContext.state !== 'closed') void audioContext.close();
  }, { once: true });
}
document.addEventListener('DOMContentLoaded', initSelectionSound);

